"""
RUN
===
The single entry point for the urban mobility RL simulation.

Usage
-----
    # Prepare data for a city (reads from data/raw/<city>/)
    python run.py --pipeline bonn

    # Resume pipeline from a specific step
    python run.py --pipeline bonn --from-step 5

    # Train a new model on a city's formatted data
    python run.py --train bonn

    # Train with custom parameters
    python run.py --train bonn --timesteps 2000000 --n_envs 12

    # Simulate with the latest model trained on a city
    python run.py --sim bonn

    # Simulate with a specific model
    python run.py --sim bonn --model 2 --n_sims 300
  python run.py --sim bonn --model 2 --n_sims 300 --use_grid

Data structure
--------------
    data/raw/<city>/
        <any>.pbf        <- download from BBBike or Geofabrik
        config.json      <- {"bbox": [min_lon, min_lat, max_lon, max_lat]}

    data/formatted/<city>/
        spatial_cache_filtered.pkl   <- generated by --pipeline
        air_distance_cache.pkl
        poi_density_cache.pkl

    output/
        model/model_0.zip, model_1.zip ...
        sim/model_0_sim_0/, model_0_sim_1/ ...
"""

import sys
import os
import argparse

# =============================================================================
# PATH SETUP
# =============================================================================

_ROOT = os.path.dirname(os.path.abspath(__file__))
_SRC  = os.path.join(_ROOT, "src")
_MAP  = os.path.join(_ROOT, "map")

for _p in [_ROOT, _SRC, _MAP] + [
    os.path.join(_SRC, d) for d in ("simulation", "spatial", "analysis")
]:
    if os.path.isdir(_p) and _p not in sys.path:
        sys.path.insert(0, _p)

# =============================================================================
# EARLY CITY DETECTION
# =============================================================================
# Set MOBILITY_CITY before any imports so config.py reads it correctly.
# We parse city from sys.argv directly -- before argparse runs.
def _detect_city():
    for flag in ("--train", "--sim", "--pipeline"):
        if flag in sys.argv:
            idx = sys.argv.index(flag)
            if idx + 1 < len(sys.argv) and not sys.argv[idx + 1].startswith("-"):
                return sys.argv[idx + 1]
    return None

_early_city = _detect_city()
if _early_city:
    os.environ["MOBILITY_CITY"] = _early_city


# =============================================================================
# MODEL / SIM NAMING
# =============================================================================

def _model_dir(city):
    d = os.path.join(_ROOT, "output", city, "model")
    os.makedirs(d, exist_ok=True)
    return d


def _next_model_index(city):
    d = _model_dir(city)
    indices = []
    for f in os.listdir(d):
        if f.startswith("model_") and f.endswith(".zip"):
            try:
                indices.append(int(f.replace("model_", "").replace(".zip", "")))
            except ValueError:
                pass
    return max(indices) + 1 if indices else 0


def _latest_model_index(city):
    d = _model_dir(city)
    indices = []
    for f in os.listdir(d):
        if f.startswith("model_") and f.endswith(".zip"):
            try:
                indices.append(int(f.replace("model_", "").replace(".zip", "")))
            except ValueError:
                pass
    if not indices:
        print(f"[ERROR] No trained models found in {d}")
        print(f"  Run: python run.py --train {city}")
        sys.exit(1)
    return max(indices)


def _model_path(city, index):
    return os.path.join(_model_dir(city), f"model_{index}.zip")


def _next_sim_index(city, model_index):
    sim_base = os.path.join(_ROOT, "output", city, "sim")
    os.makedirs(sim_base, exist_ok=True)
    prefix = f"model_{model_index}_sim_"
    indices = []
    for d in os.listdir(sim_base):
        if d.startswith(prefix) and os.path.isdir(os.path.join(sim_base, d)):
            try:
                indices.append(int(d.replace(prefix, "")))
            except ValueError:
                pass
    return max(indices) + 1 if indices else 0


def _sim_output_dir(city, model_index, sim_index):
    d = os.path.join(_ROOT, "output", city, "sim",
                     f"model_{model_index}_sim_{sim_index}")
    os.makedirs(d, exist_ok=True)
    return d


# =============================================================================
# COMMANDS
# =============================================================================

def cmd_pipeline(city, from_step):
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "pipeline", os.path.join(_MAP, "pipeline.py")
    )
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    mod.run_pipeline(city=city, from_step=from_step)


def cmd_train(city, timesteps, n_envs, lr, seed):
    # Set city via environment variable -- propagates to all subprocess workers
    os.environ["MOBILITY_CITY"] = city

    # Run data_setup check
    from data_setup import main as _setup
    _setup()

    model_idx  = _next_model_index(city)
    model_path = _model_path(city, model_idx)

    print(f"\n{'=' * 60}")
    print(f"  TRAINING -- {city}")
    print(f"  Model -> output/{city}/model/model_{model_idx}.zip")
    print(f"{'=' * 60}\n")

    from train import train as _train
    _train(
        total_timesteps = timesteps,
        n_envs          = n_envs,
        learning_rate   = lr,
        seed            = seed,
        save_path       = model_path,
        log_dir         = os.path.join(_ROOT, "output", city, "logs"),
    )
    print(f"\n[OK] Model saved: output/{city}/model/model_{model_idx}.zip")
    print(f"  To simulate: python run.py --sim {city} --model {model_idx}")


def cmd_sim(city, model_index, n_sims, n_individual, n_maps, use_grid=False):
    # Set city via environment variable -- propagates to all subprocess workers
    os.environ["MOBILITY_CITY"] = city
    # Use custom_settings default if not specified via CLI
    if n_sims is None:
        from custom_settings import N_SIMULATIONS
        n_sims = N_SIMULATIONS

    mpath = _model_path(city, model_index)
    if not os.path.exists(mpath):
        print(f"[ERROR] Model not found: {mpath}")
        available = [f for f in os.listdir(_model_dir(city))
                     if f.startswith("model_") and f.endswith(".zip")]
        if available:
            print(f"  Available: {', '.join(sorted(available))}")
        sys.exit(1)

    sim_idx    = _next_sim_index(city, model_index)
    output_dir = _sim_output_dir(city, model_index, sim_idx)

    print(f"\n{'=' * 60}")
    print(f"  SIMULATION -- {city}")
    print(f"  Model:  output/{city}/model/model_{model_index}.zip")
    print(f"  Output: output/{city}/sim/model_{model_index}_sim_{sim_idx}/")
    print(f"{'=' * 60}\n")

    from sim import main as _sim_main
    _sim_main(
        model_path         = mpath,
        n_simulations      = n_sims,
        output_dir         = output_dir,
        n_individual_plots = n_individual,
        n_trajectory_maps  = n_maps,
        use_grid           = use_grid,
    )
    print(f"\n[OK] Output: output/{city}/sim/model_{model_index}_sim_{sim_idx}/")


# =============================================================================
# CLI
# =============================================================================

def main():
    parser = argparse.ArgumentParser(
        description="Urban Mobility RL Simulation",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python run.py --pipeline bonn
  python run.py --pipeline bonn --from-step 5
  python run.py --train bonn
  python run.py --train bonn --timesteps 2000000 --n_envs 12
  python run.py --sim bonn
  python run.py --sim bonn --model 2 --n_sims 300
  python run.py --sim bonn --model 2 --n_sims 300 --use_grid
        """
    )

    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--pipeline", metavar="CITY",
                      help="Run data pipeline for data/raw/<city>/")
    mode.add_argument("--train",    metavar="CITY",
                      help="Train a new model on data/formatted/<city>/")
    mode.add_argument("--sim",      metavar="CITY",
                      help="Run simulation for <city>")

    parser.add_argument("--from-step",  type=int,   default=1,
                        help="Pipeline step to start from (default: 1)")
    parser.add_argument("--timesteps",  type=int,   default=1_000_000)
    parser.add_argument("--n_envs",     type=int,   default=8)
    parser.add_argument("--lr",         type=float, default=3e-4)
    parser.add_argument("--seed",       type=int,   default=42)
    parser.add_argument("--model",      type=int,   default=None,
                        help="Model index for --sim (default: latest)")
    parser.add_argument("--n_sims",     type=int,   default=100)
    parser.add_argument("--n_individual", type=int, default=5)
    parser.add_argument("--n_maps",     type=int,   default=3)
    parser.add_argument("--use_grid",   action="store_true",
                        help="Enable 500m grid abstraction layer")

    args = parser.parse_args()

    if args.pipeline:
        cmd_pipeline(args.pipeline, args.from_step)

    elif args.train:
        cmd_train(args.train, args.timesteps, args.n_envs, args.lr, args.seed)

    elif args.sim:
        city      = args.sim
        model_idx = args.model if args.model is not None else _latest_model_index(city)
        cmd_sim(city, model_idx, args.n_sims, args.n_individual, args.n_maps, args.use_grid)


if __name__ == "__main__":
    main()
