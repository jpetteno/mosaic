@functools.lru_cache(maxsize=None)
def is_location_open(location_type: str, hour: int, day_of_week: int) -> bool:
    if location_type in ("HOME", "WORK"):
        return _is_location_open_coarse(location_type, hour, day_of_week)
    from semantic_enrichment import ACTIVITY_PROBABILITIES, is_subactivity_open
    sub_activities = list(ACTIVITY_PROBABILITIES.get(location_type, {}).keys())
    if not sub_activities:
        return _is_location_open_coarse(location_type, hour, day_of_week)
    return any(
        is_subactivity_open(sub, float(hour), day_of_week)
        for sub in sub_activities
    )


@functools.lru_cache(maxsize=None)
def _is_location_open_coarse(location_type: str, hour: int, day_of_week: int) -> bool:
    day_type = "weekend" if day_of_week >= 5 else "weekday"
    open_hour, close_hour = OPERATING_HOURS[location_type][day_type]
    if open_hour == close_hour == 0:
        return False
    return open_hour <= hour < close_hour


def compute_tc_reward(activity_type: str, hour: float, day_of_week: int) -> float:
    """Retained for reference. Not called during training."""
    if activity_type not in TC_SCHEDULES:
        return 0.0
    day_type = "weekend" if day_of_week >= 5 else "weekday"
    schedules = TC_SCHEDULES[activity_type][day_type]
    total = 0.0
    for s in schedules:
        mean, std, scale = float(s["mean"]), float(s["std"]), float(s["scale"])
        start, end = s["range"]
        wrap = bool(s.get("wrap", False))
        in_range = (hour >= start or hour < end) if wrap else (start <= hour < end)
        if not in_range:
            continue
        h = hour + 24.0 if (wrap and hour < start) else hour
        pdf_val = float(norm.pdf(h, loc=mean, scale=std))
        pdf_max = float(norm.pdf(mean, loc=mean, scale=std))
        total += (pdf_val / pdf_max if pdf_max > 0 else 0.0) * scale
    return float(total)


