def validate_config() -> None:
    assert all(
        0 <= float(p) <= 1
        for needs in NEEDS_PROBABILITIES.values()
        for p in needs.values()
    ), "NEEDS_PROBABILITIES: all values must be in [0, 1]"
    assert all(
        0 <= float(p) <= 1
        for day_probs in DOUBLE_NEED_PROBS.values()
        for p in day_probs.values()
    ), "DOUBLE_NEED_PROBS: all values must be in [0, 1]"
    total = float(sum(EXPECTED_DISTRIBUTION.values()))
    assert abs(total - 1.0) < 0.01, f"EXPECTED_DISTRIBUTION must sum to 1.0, got {total}"
    for loc in LOCATION_TYPES:
        assert loc in OPERATING_HOURS,       f"{loc} missing from OPERATING_HOURS"
        assert loc in ACTIVITY_DURATIONS,    f"{loc} missing from ACTIVITY_DURATIONS"
        assert loc in EXPECTED_DISTRIBUTION, f"{loc} missing from EXPECTED_DISTRIBUTION"
    assert "TRAVEL" in EXPECTED_DISTRIBUTION
    assert OBS_DIM == 25,   f"OBS_DIM should be 25, got {OBS_DIM}"
    assert NUM_PHASES == 6, f"Expected 6 phases, got {NUM_PHASES}"
    for phase in range(NUM_PHASES):
        assert phase in PHASE_ACTIVITY_REWARD, f"Phase {phase} missing from PHASE_ACTIVITY_REWARD"
        for macro in ["WORK", "FOOD", "ERRAND", "LEISURE", "HOME"]:
            assert macro in PHASE_ACTIVITY_REWARD[phase],                 f"Macro {macro} missing from phase {phase} in PHASE_ACTIVITY_REWARD"
    transport_probs = list(TRANSPORT_MODE_PRIOR.values())
    assert abs(sum(transport_probs) - 1.0) < 0.01,         f"TRANSPORT_MODE_PRIOR must sum to 1.0, got {sum(transport_probs)}"
    assert "foot" in TRANSPORT_MODE_SPEEDS, "TRANSPORT_MODE_SPEEDS must include foot"


